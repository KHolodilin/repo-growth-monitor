#!/bin/bash
set -euo pipefail

# Runs only on first Postgres init (empty data dir).
# Creates a non-DDL runtime role used by the long-lived backend.

RUNTIME_USER="${POSTGRES_RUNTIME_USER:-repogrowth}"
RUNTIME_PASSWORD="${POSTGRES_RUNTIME_PASSWORD:-${POSTGRES_PASSWORD}}"

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
	DO \$\$
	BEGIN
	  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${RUNTIME_USER}') THEN
	    CREATE ROLE ${RUNTIME_USER} LOGIN PASSWORD '${RUNTIME_PASSWORD}';
	  END IF;
	END
	\$\$;
	GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${RUNTIME_USER};
	GRANT USAGE ON SCHEMA public TO ${RUNTIME_USER};
	ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${RUNTIME_USER};
	ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO ${RUNTIME_USER};
EOSQL
